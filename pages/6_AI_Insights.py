"""
pages/6_AI_Insights.py
───────────────────────
Page 6: AI-generated traffic insights.
Rule-based engine always runs; Gemini/OpenAI used when API key is set.
The LLM ONLY receives pre-computed, verified bullet points — never raw data.
"""

import json
import sys
from pathlib import Path
import streamlit as st
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from src.analytics import (
    load_cleaned_data, overview_kpis, peak_periods,
    lowest_speed_sensors, weekday_vs_weekend, low_speed_events,
)
from src.ai_insights import generate_insights
from config.settings import CLEANED_DATA_PATH, REPORTS_DIR, LLM_PROVIDER

st.set_page_config(page_title="AI Insights", page_icon="💡", layout="wide")
css_path = Path(__file__).parent.parent / "assets" / "style.css"
if css_path.exists():
    st.markdown(f"<style>{css_path.read_text()}</style>", unsafe_allow_html=True)

st.markdown("## 💡 AI Traffic Insights")
st.markdown("*Intelligent summaries derived exclusively from verified analytics results.*")

# ── Provider badge ─────────────────────────────────────────────────
provider_labels = {
    "gemini":      "🟢 Gemini API (Active)",
    "openai":      "🟢 OpenAI GPT (Active)",
    "rule_based":  "🟡 Rule-Based Engine (No API key needed)",
}
st.info(f"**Insight Engine:** {provider_labels.get(LLM_PROVIDER, LLM_PROVIDER)}")

if LLM_PROVIDER == "rule_based":
    st.caption(
        "To enable LLM narrative summaries, add your `GEMINI_API_KEY` or `OPENAI_API_KEY` "
        "to the `.env` file and restart the app."
    )

@st.cache_data(ttl=3600)
def get_data():
    try:
        return load_cleaned_data()
    except Exception as e:
        st.error(f"Data not found: {e}.")
        st.stop()

df = get_data()

# ── Load model metrics if available ────────────────────────────────
model_metrics = None
metrics_path = Path(REPORTS_DIR) / "model_metrics.json"
if metrics_path.exists():
    with open(metrics_path) as f:
        model_metrics = json.load(f)

# ── Compute analytics ───────────────────────────────────────────────
with st.spinner("Analysing traffic data …"):
    kpis       = overview_kpis(df)
    peaks      = peak_periods(df)
    low_sens   = lowest_speed_sensors(df, n=10)
    wk_wke     = weekday_vs_weekend(df)

    # Low-speed events (cached separately as it's slow)
    @st.cache_data(ttl=3600)
    def get_events(path):
        d = load_cleaned_data(path)
        return low_speed_events(d, threshold_mph=30.0, min_duration_min=15)

    events = get_events(str(CLEANED_DATA_PATH))

# ── Generate insights ───────────────────────────────────────────────
with st.spinner("Generating insights …"):
    result = generate_insights(
        kpis=kpis,
        peak_hours=peaks,
        low_sensors=low_sens,
        weekday_weekend=wk_wke,
        low_speed_events=events,
        model_metrics=model_metrics,
    )

# ── Display insights ────────────────────────────────────────────────
st.markdown("### 📋 Key Findings")
for bullet in result["bullets"]:
    st.markdown(f"- {bullet}")

if result["narrative"]:
    st.divider()
    st.markdown("### 🤖 AI Executive Summary")
    st.markdown(
        f"""<div style='background:#0F2337; border:1px solid #1E3A5F; border-radius:8px;
            padding:1.5rem; line-height:1.8;'>{result['narrative']}</div>""",
        unsafe_allow_html=True,
    )
    st.caption(f"Generated by: {result['provider'].title()} API from verified analytical results.")
else:
    st.info(
        "💡 Rule-based insights are shown above. "
        "Add a Gemini/OpenAI API key to generate narrative paragraphs."
    )

st.divider()

# ── Raw data tables behind expanders ────────────────────────────────
with st.expander("📊 Supporting Data — KPI Values"):
    st.json(kpis)

with st.expander("📊 Supporting Data — Peak Hours"):
    st.dataframe(peaks, use_container_width=True)

with st.expander("📊 Supporting Data — Low-Speed Sensors"):
    st.dataframe(low_sens, use_container_width=True)

with st.expander("📊 Supporting Data — Weekday vs Weekend"):
    st.dataframe(wk_wke, use_container_width=True)

if model_metrics:
    with st.expander("📊 Supporting Data — Model Metrics"):
        st.json(model_metrics)
